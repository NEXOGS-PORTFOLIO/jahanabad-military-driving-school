resources.bn.ui = uiBangla;
resources.en.ui = Object.fromEntries(Object.keys(uiBangla).map(key => [key, key]));

const getSavedLanguage = () => {
  try {
    return localStorage.getItem('language') === 'en' ? 'en' : 'bn';
  } catch {
    return 'bn';
  }
};

const syncLanguage = (language) => {
  document.documentElement.lang = language;
  try {
    localStorage.setItem('language', language);
  } catch {
    // Switching remains available when browser storage is disabled.
  }
};

i18n.on('languageChanged', syncLanguage);

i18n
  .use(initReactI18next)
  .init({
    resources,
    lng: getSavedLanguage(),
    supportedLngs: ['bn', 'en'],
    fallbackLng: 'en',
    interpolation: {
      escapeValue: false
    }
  });

document.documentElement.lang = i18n.language;

window.addEventListener('storage', (event) => {
  if (event.key === 'language' && ['bn', 'en'].includes(event.newValue) && event.newValue !== i18n.language) {
    i18n.changeLanguage(event.newValue);
  }
});

export default i18n;
